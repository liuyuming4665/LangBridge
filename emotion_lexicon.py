def detect_emotion(text):
    """返回 [{big, small, words}]，命中词去重。"""
    found = []
    for big, smalls in EMOTION_LEXICON.items():
        for small, words in smalls.items():
            hits = sorted({w for w in words if w in text})
            if hits:
                found.append({"big": big, "small": small, "words": hits})
    return found


